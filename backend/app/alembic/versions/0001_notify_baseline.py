_STATUS_GUARD_FUNCTION = """
CREATE OR REPLACE FUNCTION appointment_status_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.status IS DISTINCT FROM OLD.status THEN
        IF NOT (
            (OLD.status = 'BOOKED' AND NEW.status IN ('CONFIRMED', 'ARRIVED', 'CANCELLED', 'NO_SHOW'))
            OR (OLD.status = 'CONFIRMED' AND NEW.status IN ('ARRIVED', 'CANCELLED', 'NO_SHOW'))
            OR (OLD.status = 'ARRIVED' AND NEW.status = 'COMPLETED')
        ) THEN
            RAISE EXCEPTION
                'ILLEGAL_STATE_TRANSITION: % -> % is not a permitted transition',
                OLD.status, NEW.status
                USING ERRCODE = 'check_violation';
        END IF;
    END IF;
    IF (NEW.tenant_id, NEW.contact_id, NEW.practitioner_id, NEW.type, NEW.source,
        NEW.starts_at, NEW.ends_at, NEW.created_by, NEW.created_at)
       IS DISTINCT FROM
       (OLD.tenant_id, OLD.contact_id, OLD.practitioner_id, OLD.type, OLD.source,
        OLD.starts_at, OLD.ends_at, OLD.created_by, OLD.created_at) THEN
        RAISE EXCEPTION 'APPOINTMENT_IMMUTABLE: only the status of a booking can change'
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$
"""


def _create_role(name: str) -> None:
    # Idempotent, and attributes are set only at creation: a deployment may have granted the role to
    # a login user out of band, and nothing here should undo that on a re-run.
    op.execute(
        "DO $$ BEGIN "
        f"IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '{name}') THEN "
        f"CREATE ROLE {name} NOSUPERUSER NOBYPASSRLS NOCREATEROLE NOCREATEDB NOLOGIN; "
        "END IF; END $$"
    )


def _standard_policies(table: str) -> None:
    op.execute(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY")
    op.execute(f"ALTER TABLE {table} FORCE ROW LEVEL SECURITY")
    op.execute(
        f"CREATE POLICY pol_{table}_tenant_access ON {table} AS PERMISSIVE FOR ALL TO PUBLIC "
        f"USING ({_TENANT_MATCH}) WITH CHECK ({_TENANT_MATCH})"
    )
    op.execute(
        f"CREATE POLICY pol_{table}_tenant_isolation ON {table} AS RESTRICTIVE FOR ALL TO PUBLIC "
        f"USING ({_TENANT_MATCH}) WITH CHECK ({_TENANT_MATCH})"
    )


